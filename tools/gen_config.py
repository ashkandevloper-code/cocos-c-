#!/usr/bin/env python3
"""Writes Classes/config/NxConfig.generated.h from environment variables (used by CI before Gradle runs).

Only public values belong here (Supabase anon/publishable keys are designed to ship in apps; RLS protects data).
"""
import os
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
KEYS = ["SUPABASE_URL", "SUPABASE_ANON_KEY", "GAMES_SUPABASE_URL", "GAMES_SUPABASE_ANON_KEY", "LIVEKIT_URL"]
DEFAULTS = {"LIVEKIT_URL": "wss://nexora-space-xzjzlfyl.livekit.cloud"}


def esc(v: str) -> str:
    return v.replace("\\", "\\\\").replace('"', '\\"')


def main() -> int:
    out = ROOT / "Classes" / "config" / "NxConfig.generated.h"
    lines = ["// Generated by tools/gen_config.py. Do not edit or commit.", "#pragma once"]
    for k in KEYS:
        v = os.environ.get(k, DEFAULTS.get(k, ""))
        lines.append(f'#define NX_CFG_{k} "{esc(v)}"')
        shown = (v[:12] + "...") if "KEY" in k and v else (v or "<empty>")
        print(f"  {k} = {shown}")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out}")
    if not os.environ.get("SUPABASE_URL"):
        print("warning: SUPABASE_URL is empty -> the app runs offline-only", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
